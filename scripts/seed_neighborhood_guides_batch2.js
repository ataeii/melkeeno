async function main() {
  if (!process.env.MONGODB_URI) {
    console.error('MONGODB_URI not set');
    process.exit(1);
  }
  await mongoose.connect(process.env.MONGODB_URI);
  const col = mongoose.connection.collection('articles');

  let createdAt = new Date('2026-09-08T09:00:00.000Z'); // later than current top (2026-09-07T18:00:00Z)
  for (const article of articles) {
    await col.updateOne(
      { slug: article.slug },
      { $set: { ...article, createdAt, updatedAt: createdAt } },
      { upsert: true }
    );
    console.log('upserted:', article.slug, '-', createdAt.toISOString());
    createdAt = new Date(createdAt.getTime() + 60 * 60 * 1000); // +1h each, so later ones sort higher
  }

  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
