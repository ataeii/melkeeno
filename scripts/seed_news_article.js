async function main() {
  if (!process.env.MONGODB_URI) {
    console.error('MONGODB_URI not set');
    process.exit(1);
  }
  await mongoose.connect(process.env.MONGODB_URI);
  const saved = await Article.findOneAndUpdate({ slug: article.slug }, article, { upsert: true, new: true });
  console.log('published:', saved.slug, '-', saved.createdAt.toISOString());
  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
