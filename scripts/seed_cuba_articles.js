async function main() {
  if (!process.env.MONGODB_URI) {
    console.error('MONGODB_URI not set');
    process.exit(1);
  }
  await mongoose.connect(process.env.MONGODB_URI);
  const col = mongoose.connection.collection('articles');
  for (const a of articles) {
    const { date, ...fields } = a;
    const createdAt = new Date(`${date}T12:00:00Z`);
    await col.updateOne(
      { slug: a.slug },
      { $set: { ...fields, status: 'published', createdAt, updatedAt: createdAt } },
      { upsert: true }
    );
    console.log('upserted:', a.slug);
  }
  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
