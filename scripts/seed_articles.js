async function main() {
  if (!process.env.MONGODB_URI) {
    console.error('MONGODB_URI not set (expected in .env.local)');
    process.exit(1);
  }
  await mongoose.connect(process.env.MONGODB_URI);
  for (const a of articles) {
    await Article.findOneAndUpdate({ slug: a.slug }, a, { upsert: true, new: true });
    console.log('upserted:', a.slug);
  }
  console.log(`\nDone. ${articles.length} articles upserted as drafts.`);
  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
