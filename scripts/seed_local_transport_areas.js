async function main() {
  if (!process.env.MONGODB_URI) {
    console.error('MONGODB_URI not set');
    process.exit(1);
  }
  await mongoose.connect(process.env.MONGODB_URI);
  const col = mongoose.connection.collection('articles');
  const createdAt = new Date('2026-09-09T18:00:00.000Z'); // deliberately later than the current top article (2026-09-08T09:00:00Z, neighborhood batch2's last)
  await col.updateOne(
    { slug: article.slug },
    { $set: { ...article, createdAt, updatedAt: createdAt } },
    { upsert: true }
  );
  console.log('upserted:', article.slug, '-', createdAt.toISOString());
  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
